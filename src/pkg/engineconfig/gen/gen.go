// Package gen turns an extract.Manifest into a Go struct source file: one field per resolved,
// non-alias flag, tagged with the flag's real kebab-case name as its yaml key. See
// docs/agent/design-config-codegen.md -- the flag name, not the Go field name, is the
// source of truth for what a valid config.yaml key looks like.
package gen

import (
	"bytes"
	"go/format"
	"sort"
	"strings"
	"text/template"

	"github.com/colonel-byte/cargoship/src/pkg/engineconfig/extract"
)

// Options configures one generated struct file.
type Options struct {
	PackageName string // must already be a valid Go package identifier
	StructName  string
	Manifest    extract.Manifest
}

type templateField struct {
	GoName   string
	YAMLName string
	GoType   string
	Hidden   bool
	Aliases  []string
}

type templateData struct {
	PackageName string
	StructName  string
	Distro      string
	Version     string
	Target      string
	Fields      []templateField
	Unresolved  []string
}

var tmpl = template.Must(template.New("struct").Funcs(template.FuncMap{"join": strings.Join}).Parse(`// Copyright 2026 colonel-byte
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// Code generated by mage generate:engineConfig from {{.Distro}} {{.Version}} ({{.Target}}). DO NOT EDIT.

package {{.PackageName}}
{{if .Unresolved}}
// Flags not resolvable from the extracted source and therefore absent below:
{{range .Unresolved}}//   - {{.}}
{{end}}{{end}}
// {{.StructName}} is the {{.Target}} config.yaml key set for {{.Distro}} {{.Version}}.
type {{.StructName}} struct {
{{range .Fields}}{{if .Hidden}}	// Deprecated: hidden flag.
{{end}}{{if .Aliases}}	// Aliases (not separately validated here): {{join .Aliases ", "}}
{{end}}	{{.GoName}} {{.GoType}} ` + "`yaml:\"{{.YAMLName}},omitempty\"`" + `
{{end}}}
`))

// Generate renders and gofmt's the struct source for opts.Manifest.
func Generate(opts Options) ([]byte, error) {
	data := templateData{
		PackageName: opts.PackageName,
		StructName:  opts.StructName,
		Distro:      opts.Manifest.Distro,
		Version:     opts.Manifest.Version,
		Target:      opts.Manifest.Target,
	}

	byDestination := map[string]int{} // destination -> index into data.Fields
	for _, f := range opts.Manifest.Flags {
		switch {
		case f.Unresolved:
			data.Unresolved = append(data.Unresolved, f.Name)
		case f.AliasOf != "":
			if idx, ok := byDestination[f.Destination]; ok {
				data.Fields[idx].Aliases = append(data.Fields[idx].Aliases, f.Name)
			}
		default:
			goType := f.Type
			if f.UnknownType {
				goType = "string"
			}
			if f.Slice {
				goType = "[]" + goType
			}
			data.Fields = append(data.Fields, templateField{
				GoName:   goFieldName(f.Name),
				YAMLName: f.Name,
				GoType:   goType,
				Hidden:   f.Hidden,
			})
			if f.Destination != "" {
				byDestination[f.Destination] = len(data.Fields) - 1
			}
		}
	}
	sort.Strings(data.Unresolved)

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}

	return format.Source(buf.Bytes())
}

// goFieldName converts a kebab-case flag name (e.g. "kube-apiserver-arg") into an exported Go
// identifier (e.g. "KubeApiserverArg"). It deliberately does not special-case acronyms: the
// yaml tag, not the Go field name, is what config.yaml authors and validators care about.
func goFieldName(flagName string) string {
	parts := strings.Split(flagName, "-")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}
