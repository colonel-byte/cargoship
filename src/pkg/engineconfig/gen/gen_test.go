func TestGenerateProducesValidFormattedGo(t *testing.T) {
	m := extract.Manifest{
		Distro:  "k3s",
		Version: "v1.35.3-k3s1",
		Target:  "server",
		Flags: []extract.Flag{
			{Name: "cluster-cidr", Type: "string", Slice: true, Destination: "&ServerConfig.ClusterCIDR"},
			{Name: "https-listen-port", Type: "int", Value: "6443"},
			{Name: "tls-san-security", Type: "bool", Value: "true"},
			{
				Name: "kube-controller-manager-arg", Type: "string", Slice: true,
				Destination: "&ServerConfig.ExtraControllerArgs",
			},
			{
				Name: "kube-controller-arg", Type: "string", Slice: true, Hidden: true,
				Destination: "&ServerConfig.ExtraControllerArgs", AliasOf: "kube-controller-manager-arg",
			},
			{Name: "ConfigFlag", Unresolved: true},
			{Name: "DebugFlag", Unresolved: true},
		},
	}

	out, err := Generate(Options{PackageName: "v1_35_3_k3s1", StructName: "ServerConfig", Manifest: m})
	require.NoError(t, err)

	// Generate already runs format.Source; re-running it must be a no-op if the output is
	// actually valid, well-formatted Go.
	formatted, err := format.Source(out)
	require.NoError(t, err)
	require.Equal(t, string(formatted), string(out))

	src := string(out)
	require.Contains(t, src, "package v1_35_3_k3s1")
	require.Contains(t, src, "Code generated by mage generate:engineConfig from k3s v1.35.3-k3s1 (server). DO NOT EDIT.")
	require.Contains(t, src, "ClusterCidr")
	require.Contains(t, src, `yaml:"cluster-cidr,omitempty"`)
	require.Contains(t, src, "HttpsListenPort")
	require.Contains(t, src, `yaml:"https-listen-port,omitempty"`)
	require.Contains(t, src, "TlsSanSecurity")
	require.Contains(t, src, `yaml:"tls-san-security,omitempty"`)

	// The alias's own Destination-sharing field is skipped; it's noted as a comment on the
	// canonical field instead, not duplicated as its own struct field.
	require.NotContains(t, src, "kube-controller-arg,omitempty")
	require.Contains(t, src, "Aliases (not separately validated here): kube-controller-arg")

	// Unresolved flags are listed for visibility, sorted, and don't produce struct fields.
	require.Contains(t, src, "//   - ConfigFlag")
	require.Contains(t, src, "//   - DebugFlag")
}

func TestGoFieldName(t *testing.T) {
	cases := map[string]string{
		"cluster-cidr":            "ClusterCidr",
		"kube-apiserver-arg":      "KubeApiserverArg",
		"selinux":                 "Selinux",
		"tls-san":                 "TlsSan",
		"write-kubeconfig-mode":   "WriteKubeconfigMode",
		"protect-kernel-defaults": "ProtectKernelDefaults",
	}
	for in, want := range cases {
		require.Equal(t, want, goFieldName(in), in)
	}
}
