package gen

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/colonel-byte/cargoship/pkg/engineconfig/extract"
)

// NestedKeysOptions configures one generated nested-key-tree file.
type NestedKeysOptions struct {
	PackageName string // must already be a valid Go package identifier
	VarName     string // exported Go identifier for the generated var
	Distro      string
	Version     string
	RootType    string // the source struct this tree was extracted from, e.g. "ClusterConfiguration"
	Node        extract.FieldNode
}

// nestedCodeGeneratedComment is spliced by concatenation, not written as a raw string line, for
// the same reason gen.go's codeGeneratedComment is -- see there.
const nestedCodeGeneratedComment = "// Code generated by mage generate:engineConfig from %s %s (%s). DO NOT EDIT."

// GenerateNestedKeys renders and gofmt's opts.Node as a literal extract.FieldNode value, unlike
// Generate (a real Go struct consumed via reflect): upstream's config document is genuinely
// nested, so what's extracted is a key tree, not a flag set, and there's no struct shape to
// declare -- the tree itself is what gets consumed at validation time.
func GenerateNestedKeys(opts NestedKeysOptions) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Copyright 2026 colonel-byte\n")
	b.WriteString("//\n")
	b.WriteString("// Licensed under the Apache License, Version 2.0 (the \"License\");\n")
	b.WriteString("// you may not use this file except in compliance with the License.\n")
	b.WriteString("// You may obtain a copy of the License at\n")
	b.WriteString("//\n")
	b.WriteString("//     http://www.apache.org/licenses/LICENSE-2.0\n")
	b.WriteString("//\n")
	b.WriteString("// Unless required by applicable law or agreed to in writing, software\n")
	b.WriteString("// distributed under the License is distributed on an \"AS IS\" BASIS,\n")
	b.WriteString("// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n")
	b.WriteString("// See the License for the specific language governing permissions and\n")
	b.WriteString("// limitations under the License.\n\n")

	fmt.Fprintf(&b, nestedCodeGeneratedComment, opts.Distro, opts.Version, opts.RootType)
	b.WriteString("\n\n")
	fmt.Fprintf(&b, "package %s\n\n", opts.PackageName)
	fmt.Fprintf(&b, "import \"github.com/colonel-byte/cargoship/pkg/engineconfig/extract\"\n\n")
	fmt.Fprintf(&b, "// %s is the nested key tree extracted from %s's %s for %s %s.\n",
		opts.VarName, opts.Distro, opts.RootType, opts.Distro, opts.Version)
	fmt.Fprintf(&b, "var %s = ", opts.VarName)
	writeFieldNode(&b, opts.Node)
	b.WriteString("\n")

	return format.Source([]byte(b.String()))
}

// writeFieldNode writes node as a Go literal expression of type extract.FieldNode, one child per
// line so a generated tree reads like a tree instead of a single unreadable line -- format.Source
// keeps a composite literal multi-line as long as its source already breaks after each element,
// so the line breaks here are what make that happen, not indentation (gofmt fixes that up).
func writeFieldNode(b *strings.Builder, node extract.FieldNode) {
	if node.Children == nil {
		b.WriteString("extract.FieldNode{}")
		return
	}

	names := make([]string, 0, len(node.Children))
	for name := range node.Children {
		names = append(names, name)
	}
	sort.Strings(names)

	b.WriteString("extract.FieldNode{Children: map[string]extract.FieldNode{\n")
	for _, name := range names {
		fmt.Fprintf(b, "%q: ", name)
		writeFieldNode(b, node.Children[name])
		b.WriteString(",\n")
	}
	b.WriteString("}}")
}
